a = 5
b = 2

# 산술 연산자
print(a + b)    # 7 덧셈
print(a - b)    # 3 뺄셈
print(a * b)    # 10 곱셈
print(a / b)    # 2.5 나눗셈
print(a // b)   # 2 몫
print(a % b)    # 1 나머지
print(a ** b)   # 25 거듭제곱

# 문자열 연산
a = "hello"
b = "world"
print(a + b)    # helloworld (이어붙이기)
print(a * 2)    # hellohello (반복)

# 복합 대입 연산자
score = 0

score += 10     # 10 (score = score + 10)
score -= 3      # 7 (score = score - 3)
score *= 2      # 14 (score = score * 2)
score /= 2      # 7.0 (score = score / 2)